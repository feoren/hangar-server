//! Small stateless helpers: time, randomness, encoding, hashes.

use std::time::{SystemTime, UNIX_EPOCH};

use base64::engine::general_purpose::URL_SAFE_NO_PAD;
use base64::Engine;
use hmac::{Hmac, Mac};
use sha2::{Digest, Sha256};

/// Unix time in milliseconds according to the server clock.
pub fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| u64::try_from(d.as_millis()).unwrap_or(u64::MAX))
        .unwrap_or(0)
}

/// Unix time in seconds.
pub fn now_s() -> i64 {
    i64::try_from(now_ms() / 1000).unwrap_or(i64::MAX)
}

/// Cryptographically secure random bytes from the operating system. A failure here cannot be
/// recovered from (no randomness means no secure tokens), so the call panics.
pub fn random_bytes<const N: usize>() -> [u8; N] {
    let mut out = [0u8; N];
    #[allow(clippy::expect_used)]
    getrandom::fill(&mut out)
        .expect("the operating system's random number generator is unavailable");
    out
}

/// 32 random bytes as base64url without padding (43 characters).
pub fn random_token() -> String {
    b64(&random_bytes::<32>())
}

/// 16 random bytes as base64url (22 characters); for identifiers that are not secrets.
pub fn random_id() -> String {
    b64(&random_bytes::<16>())
}

pub fn b64(bytes: &[u8]) -> String {
    URL_SAFE_NO_PAD.encode(bytes)
}

/// Strict base64url without padding; anything else is an error.
pub fn unb64(text: &str) -> Option<Vec<u8>> {
    URL_SAFE_NO_PAD.decode(text.as_bytes()).ok()
}

pub fn sha256(bytes: &[u8]) -> [u8; 32] {
    Sha256::digest(bytes).into()
}

pub fn hex(bytes: &[u8]) -> String {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(char::from(DIGITS[usize::from(byte >> 4)]));
        out.push(char::from(DIGITS[usize::from(byte & 0x0f)]));
    }
    out
}

/// SHA-256 of a token as hex; this is how tokens are stored in the database.
pub fn token_hash(token: &str) -> String {
    hex(&sha256(token.as_bytes()))
}

/// HMAC-SHA256 with the server secret, as hex.
pub fn hmac_hex(key: &[u8], parts: &[&[u8]]) -> String {
    #[allow(clippy::expect_used)]
    let mut mac = Hmac::<Sha256>::new_from_slice(key).expect("HMAC accepts keys of any length");
    for part in parts {
        let len = u32::try_from(part.len()).unwrap_or(u32::MAX);
        mac.update(&len.to_be_bytes());
        mac.update(part);
    }
    hex(&mac.finalize().into_bytes())
}

/// Constant-time comparison.
pub fn ct_eq(a: &[u8], b: &[u8]) -> bool {
    use subtle::ConstantTimeEq;
    a.len() == b.len() && bool::from(a.ct_eq(b))
}

/// Identifiers generated by the server or a client: `[A-Za-z0-9_-]`, 1 to `max` characters.
pub fn is_id(value: &str, max: usize) -> bool {
    !value.is_empty()
        && value.len() <= max
        && value
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

/// Opaque external identifiers (project and account ID of the website): no control characters.
pub fn is_opaque(value: &str, max: usize) -> bool {
    !value.is_empty() && value.len() <= max && !value.chars().any(char::is_control)
}

/// Normalizes an email address for comparisons (lowercase, trimmed). Roughly checks the shape:
/// exactly one `@`, both parts non-empty, no whitespace or control characters, at most
/// 254 characters.
pub fn normalize_email(raw: &str) -> Option<String> {
    let email = raw.trim().to_lowercase();
    if email.len() > 254 || email.chars().any(|c| c.is_whitespace() || c.is_control()) {
        return None;
    }
    let (local, domain) = email.split_once('@')?;
    if local.is_empty() || domain.len() < 3 || domain.contains('@') || !domain.contains('.') {
        return None;
    }
    if domain.starts_with('.') || domain.ends_with('.') || local.contains(['<', '>', '"', ',', ';'])
    {
        return None;
    }
    Some(email)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn email_is_normalized_and_checked() {
        assert_eq!(
            normalize_email(" A@Example.ORG "),
            Some("a@example.org".into())
        );
        assert_eq!(normalize_email("a@b"), None);
        assert_eq!(normalize_email("a b@example.org"), None);
        assert_eq!(normalize_email("a@@example.org"), None);
        assert_eq!(normalize_email("<a>@example.org"), None);
        assert_eq!(normalize_email("a@example.org\r\nBcc: x@y.z"), None);
    }

    #[test]
    fn identifiers() {
        assert!(is_id("abc-DEF_09", 64));
        assert!(!is_id("", 64));
        assert!(!is_id("a b", 64));
        assert!(is_opaque("projekt 12 / ä", 128));
        assert!(!is_opaque("a\nb", 128));
    }

    #[test]
    fn base64url_is_strict() {
        assert_eq!(unb64(&b64(b"hangar")), Some(b"hangar".to_vec()));
        assert_eq!(unb64("aGFuZ2Fy="), None);
        assert_eq!(unb64("aGFu+2Fy"), None);
    }
}
