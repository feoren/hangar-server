pub fn strings(lang: &str) -> &'static Strings {
    match lang {
        "de" => &DE,
        "tr" => &TR,
        "fr" => &FR,
        "es" => &ES,
        "pt" => &PT,
        "el" => &EL,
        "pl" => &PL,
        "ru" => &RU,
        "ja" => &JA,
        "zh" => &ZH,
        "ar" => &AR,
        _ => &EN,
    }
}

/// Picks the language: first an explicit choice, then `Accept-Language`, otherwise the
/// server's default.
pub fn pick(explicit: Option<&str>, accept_language: Option<&str>, default: &str) -> &'static str {
    let find = |tag: &str| {
        let primary = tag
            .trim()
            .split(['-', '_', ';'])
            .next()
            .unwrap_or("")
            .to_ascii_lowercase();
        LANGS.iter().copied().find(|l| *l == primary)
    };
    if let Some(lang) = explicit.and_then(find) {
        return lang;
    }
    if let Some(header) = accept_language {
        for part in header.split(',').take(10) {
            if let Some(lang) = find(part) {
                return lang;
            }
        }
    }
    find(default).unwrap_or("en")
}

/// Fills in placeholders. Values are not interpreted any further.
pub fn fill(template: &str, values: &[(&str, &str)]) -> String {
    let mut out = template.to_owned();
    for (key, value) in values {
        out = out.replace(&format!("{{{key}}}"), value);
    }
    out
}

