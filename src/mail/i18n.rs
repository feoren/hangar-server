#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn language_choice() {
        assert_eq!(pick(Some("de-AT"), None, "en"), "de");
        assert_eq!(pick(None, Some("fr-CH, fr;q=0.9, en;q=0.8"), "en"), "fr");
        assert_eq!(pick(Some("xx"), Some("ja"), "en"), "ja");
        assert_eq!(pick(None, None, "de"), "de");
    }

    #[test]
    fn all_languages_have_all_placeholders_and_no_dashes() {
        for lang in LANGS {
            let s = strings(lang);
            assert!(
                s.invite_intro.contains("{inviter}") && s.invite_intro.contains("{team}"),
                "{lang}"
            );
            assert!(s.invite_note.contains("{days}"), "{lang}");
            assert!(s.login_note.contains("{minutes}"), "{lang}");
            assert!(
                s.accepted_intro.contains("{who}") && s.accepted_subject.contains("{who}"),
                "{lang}"
            );
            assert!(s.attention_subject.contains("{team}"), "{lang}");
            assert!(
                s.page_invite_done.contains("{email}")
                    && s.page_magic_prompt.contains("{email}")
                    && s.page_device_label.contains("{label}")
                    && s.page_devices_meta.contains("{created}")
                    && s.page_devices_meta.contains("{used}"),
                "{lang}"
            );
            for text in [
                s.invite_note,
                s.login_note,
                s.attention_note,
                s.footer,
                s.page_seats_full,
                s.page_license_required,
                s.invite_intro,
            ] {
                assert!(
                    !text.contains('\u{2013}') && !text.contains('\u{2014}'),
                    "{lang}"
                );
            }
        }
        assert!(strings("ar").rtl);
    }
}
